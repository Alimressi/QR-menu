  "on a glossy black surface, warm key light on the bottle itself, deep electric blue neon glow " +
  "in the empty dark background, subtle blue rim light along the edges, plain seamless backdrop " +
  "with nothing behind the bottle, no room, no furniture, no screens, no signage, no people, " +
  "high contrast, sharp focus, appetising, the product label sharp, accurate and correctly " +
  "spelled, turned to face the camera, 4:3 landscape aspect ratio, the whole product inside " +
  "the frame with clear space around it, no text anywhere except the product's own label";

// The blue is behind and around the food, never on it. Neon lighting a dish
// directly turns it grey — blue is the one colour food cannot be lit with — so
// the key light stays warm and the neon does the work of matching the menu,
// whose own palette is #2323FF on near black.
//
// The neon is light, not scenery. Asking for a gaming lounge got one: monitors,
// chairs, blurred players, and neon signs spelling GAME OE and ARCADE ESPORTS
// behind the bottle — a model that cannot letter a logo cannot letter a sign
// either, and the room stole the frame from the product besides. Both styles
// now ask for an empty backdrop and let the blue arrive as glow, which is the
// half of the lounge that was doing the work.
//
// Both end up 4:3, which is the shape of the card, but they get there by
// different roads. AI Studio can be asked for the ratio outright, so
// STYLE_BRANDED asks. flux-1-schnell cannot: its only inputs are the prompt
// and a step count, and it returns a square whatever the prompt says. That
// square is cropped to the card here, losing a quarter of its height, so STYLE
// asks instead for clear space above and below the food — headroom the crop
// can take without cutting into the dish.
//
// STYLE now describes that backdrop the way the finished drink photos actually
// look, rather than in the abstract: black mirror tabletop, one pool of blue
// behind the subject, black corners, a faint horizon between the two. The
// thirteen bottles are the reference the other seventy-nine are trying to
// match, and a description copied from the result is a closer brief than one
// written before anything had been shot.

